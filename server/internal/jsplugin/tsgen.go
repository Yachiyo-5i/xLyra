func renderInterface(item tsType, names map[reflect.Type]string) (string, error) {
	typ := reflect.TypeOf(item.value)
	var out strings.Builder
	fmt.Fprintf(&out, "export interface %s {\n", item.name)
	for i := 0; i < typ.NumField(); i++ {
		field := typ.Field(i)
		raw, ok := field.Tag.Lookup("ts")
		if !ok {
			return "", fmt.Errorf("%s.%s has no ts tag", typ.Name(), field.Name)
		}
		if raw == "-" {
			continue
		}
		name, optional, override, doc := parseTSTag(raw)
		tsType := override
		if tsType == "" {
			var ptr bool
			var err error
			if tsType, ptr, err = tsTypeOf(field.Type, names); err != nil {
				return "", fmt.Errorf("%s.%s: %w", typ.Name(), field.Name, err)
			}
			optional = optional || ptr
		}
		if doc != "" {
			fmt.Fprintf(&out, "  /** %s */\n", doc)
		}
		mark := ""
		if optional {
			mark = "?"
		}
		fmt.Fprintf(&out, "  %s%s: %s;\n", name, mark, tsType)
	}
	out.WriteString("}\n")
	return out.String(), nil
}

// splitTag splits a ts tag at its commas, except those inside angle brackets,
// so type=Record<string, X> stays in one piece.
func splitTag(raw string) []string {
	var parts []string
	depth, start := 0, 0
	for i, r := range raw {
		switch r {
		case '<':
			depth++
		case '>':
			depth--
		case ',':
			if depth == 0 {
				parts = append(parts, raw[start:i])
				start = i + 1
			}
		}
	}
	return append(parts, raw[start:])
}

func parseTSTag(raw string) (name string, optional bool, typ string, doc string) {
	parts := splitTag(raw)
	name = parts[0]
	for i := 1; i < len(parts); i++ {
		part := parts[i]
		switch {
		case part == "optional":
			optional = true
		case strings.HasPrefix(part, "type="):
			typ = strings.TrimPrefix(part, "type=")
		case strings.HasPrefix(part, "doc="):
			doc = strings.TrimPrefix(strings.Join(parts[i:], ","), "doc=")
			return
		}
	}
	return
}

// tsTypeOf maps a Go type to TypeScript. ptr reports a pointer, which becomes optional.
func tsTypeOf(typ reflect.Type, names map[reflect.Type]string) (string, bool, error) {
	if typ.Kind() == reflect.Pointer {
		inner, _, err := tsTypeOf(typ.Elem(), names)
		return inner, true, err
	}
	if name, ok := names[typ]; ok {
		return name, false, nil
	}
	switch typ.Kind() {
	case reflect.String:
		return "string", false, nil
	case reflect.Bool:
		return "boolean", false, nil
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Float32, reflect.Float64:
		return "number", false, nil
	case reflect.Interface:
		return "any", false, nil
	case reflect.Slice:
		inner, _, err := tsTypeOf(typ.Elem(), names)
		return inner + "[]", false, err
	case reflect.Map:
		if typ.Key().Kind() != reflect.String {
			return "", false, fmt.Errorf("map key %s is not a string", typ.Key())
		}
		inner, _, err := tsTypeOf(typ.Elem(), names)
		return "Record<string, " + inner + ">", false, err
	}
	return "", false, fmt.Errorf("unsupported type %s", typ)
}

// TypeDeclarations renders the plugin SDK .d.ts: interfaces generated from the
// Go contract structs followed by the hand-written unions and host API.
func TypeDeclarations() (string, error) {
	names := map[reflect.Type]string{}
	for _, item := range tsTypes {
		names[reflect.TypeOf(item.value)] = item.name
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// xLyra plugin API v1 (apiVersion %d, hostApi %d).\n", hookAPIVersion, hostAPIVersion)
	out.WriteString("// Code generated by `go generate ./cmd/xlyra-plugin`; DO NOT EDIT.\n")
	out.WriteString("// Import with `import type`; the bundle must not contain imports.\n\n")
	methods := make([]string, 0, len(probeMethods))
	for method := range probeMethods {
		methods = append(methods, fmt.Sprintf("%q", method))
	}
	sort.Strings(methods)
	for _, item := range tsTypes {
		if item.section != "" {
			fmt.Fprintf(&out, "// ---- %s ----\n\n", item.section)
		}
		if item.enum != nil {
			quoted := make([]string, len(item.enum.values))
			for i, value := range item.enum.values {
				quoted[i] = fmt.Sprintf("%q", value)
			}
			fmt.Fprintf(&out, "export type %s = %s;\n\n", item.enum.name, strings.Join(quoted, " | "))
		}
		if item.name == "ProbeRequest" {
			fmt.Fprintf(&out, "export type ProbeMethod = %s;\n\n", strings.Join(methods, " | "))
		}
		body, err := renderInterface(item, names)
		if err != nil {
			return "", err
		}
		out.WriteString(body)
		out.WriteString("\n")
	}
	kinds := SupportedKinds()
	quoted := make([]string, len(kinds))
	for i, info := range kinds {
		quoted[i] = fmt.Sprintf("%q", info.Name)
	}
	fmt.Fprintf(&out, "export type PluginKind = %s;\n\n", strings.Join(quoted, " | "))
	out.WriteString("export interface PluginMeta {\n  apiVersion: number;\n  id: string;\n  kind: PluginKind;\n}\n\n")
	out.WriteString(strings.TrimLeft(tsStatic, "\n"))
	if !strings.HasSuffix(out.String(), "\n") {
		out.WriteByte('\n')
	}
	out.WriteString("\n")
	out.WriteString(siteProviderHookTypes)
	return out.String(), nil
}

